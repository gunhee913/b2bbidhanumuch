/** 펼침 화살표 열 · `compact` 에서 펼침(`renderExpanded`)을 쓸 때만 맨 앞에 붙는다 */
export const COMPACT_EXPAND_COLUMN_PX = 24;

/**
 * 표가 바닥 폭보다 넓을 때 남는 폭을 열마다 **똑같이** 얹는다.
 *
 * 비율 폭(`w-[x%]`)으로 늘리면 넓은 열이 더 많이 받는다. 접수번호 칸과 상장업체 ·
 * 총 낙찰대금 뒤만 휑하게 벌어지고, 두 글자짜리 축종 · 성별은 그대로 붙어 있었다.
 * 칸마다 같은 몫을 얹어야 값 사이 간격이 고르게 보인다.
 */
export function spreadColumns(
  base: readonly number[],
  width: number,
): number[] {
  const extra = Math.max(0, width - sum(base)) / Math.max(1, base.length);
  return base.map((px) => px + extra);
}
